"""Generate C++ bases for CIP's QObject API from apps/qtclient/client/upstream/contract.

  gen_cpp.py CONTRACT_DIR OUT_DIR [--chunks N] [--qml client/upstream/qml/qmlcomponents]

Every moc class CIP exposes becomes `cip::<CIP name>` (same namespaces, same
class name) with CIP's Q_PROPERTYs, signals, slots, invokables and Q_ENUMs and
default implementations (properties are stored in m_<name>, methods return {}).
Handwritten classes subclass them under the real CIP name and are bound with
CIP_IMPLEMENT so QML instantiates them instead of the defaults.

Outputs:
  cip_fwd.h              forward declarations + cip::Impl binding trait
  cip_gen_NN.h/.cpp      the classes, topologically ordered, NN = 00..N-1
  cip_gen.h              umbrella
  cip_options.h          EClientOption ids (option_ids.json)
  cip_registration.h/.cpp registerQmlTypes(): qmlcomponents elements, TibiaEnums,
                         qmlenumvalues scopes
  cip_skipped.json       members not generated (types QML cannot carry), per class
  qrc/qt/qml/qmlcomponents/{qmldir,qml/qmldir}  module type list (with --qml)
"""

