def getter_name(prop):
    """C++ name of a property's READ function; QML still sees CIP's property name."""
    return prop + "_" if prop in CPP_KEYWORDS else prop


def split_ns(full):
    parts = full.split("::")
    return parts[:-1], parts[-1]


class Gen:
    def __init__(self, contract: Path):
        moc = json.loads((contract / "moc.json").read_text())
        self.moc = {}
        for c in moc:
            self.moc.setdefault(c["class"], c)
        self.elements = json.loads((contract / "elements.json").read_text())
        self.regs = json.loads((contract / "qml_registrations.json").read_text())
        self.options = json.loads((contract / "option_ids.json").read_text())
        self.skipped = defaultdict(list)

        self.namespaces = [c for c in self.moc.values() if c["superclass"] is None and c["enums"]]
        self.roots = {}
        for name in self.moc:
            root = self._root(name)
            if root:
                self.roots[name] = root
        self.short = defaultdict(list)
        for name in self.roots:
            self.short[split_ns(name)[1]].append(name)
        self.enum_owner = defaultdict(list)  # enum name -> [owner]
        for c in self.moc.values():
            if c["class"] in self.roots or c in self.namespaces:
                for e in c["enums"]:
                    self.enum_owner[e["name"]].append(c["class"])

    def cpp_path(self, name):
        """C++ path under cip:: (nested classes flatten to Outer_Inner)."""
        parts = name.split("::")
        for i in range(1, len(parts)):
            outer = self.moc.get("::".join(parts[:i]))
            if outer is not None and outer["superclass"] is not None:
                return "::".join(parts[:i - 1] + ["_".join(parts[i - 1:])])
        return name

    def ref(self, name):
        return f"::cip::{self.cpp_path(name)}"

    def _root(self, name, seen=()):
        c = self.moc.get(name)
        if c is None:
            return None
        sup = c["superclass"]
        if sup in QT_ROOTS:
            return sup
        if sup in self.moc and sup not in seen:
            return self._root(sup, seen + (name,))
        return None

    def ancestors(self, name):
        out = []
        while name in self.moc and self.moc[name]["superclass"] in self.moc:
            name = self.moc[name]["superclass"]
            out.append(name)
        return out

    # -- types ------------------------------------------------------------
    def resolve_class(self, t, ctx):
        t = t.lstrip(":")
        if t in self.roots:
            return t
        ns, short = split_ns(t)
        cands = self.short.get(short, [])
        if ns:
            cands = [c for c in cands if c.endswith("::".join(ns + [short]))]
        if len(cands) > 1:
            ctx_ns = split_ns(ctx)[0]
            near = [c for c in cands if split_ns(c)[0] == ctx_ns]
            cands = near or cands
        return cands[0] if len(cands) == 1 else None

    def resolve_enum(self, t, ctx, emitted):
        owner = self.enum_owner_of(t, ctx)
        if owner is None:
            return None
        if owner != ctx and owner not in emitted:
            return "int"
        return f"{self.ref(owner)}::{split_ns(t)[1]}"

    def enum_owner_of(self, t, ctx):
        t = t.strip().lstrip(":")
        if not re.fullmatch(r"[\w:]+", t):
            return None
        ns, ename = split_ns(t)
        owners = self.enum_owner.get(ename, [])
        if ns:
            qual = "::".join(ns)
            owners = [o for o in owners if o == qual or o.endswith("::" + qual)]
        if len(owners) > 1:
            pref = [ctx] + self.ancestors(ctx)
            near = [o for o in owners if o in pref] or \
                   [o for o in owners if split_ns(o)[0] == split_ns(ctx)[0]] or \
                   [o for o in owners if o == "::".join(split_ns(ctx)[0])]
            owners = near or owners
        return owners[0] if len(owners) == 1 else None

    def cpp_type(self, t, ctx, emitted):
        """C++ type for a contract type, or None when QML cannot carry it."""
        t = t.strip()
        if t.endswith("&") or t.startswith("const "):
            return None
        if t == "void" or t in VALUE_TYPES or t in CLASS_TYPES or t in QT_POINTERS or t in QT_ENUMS:
            return t
        if INT_ENUMS.match(t) or t in INT_TYPES:
            return "int"
        m = re.fullmatch(r"QList<(.+)>", t)
        if m and m.group(1) in INT_TYPES:
            return "QList<int>"
        m = re.fullmatch(r"QList<(.+)\*>", t)
        if m:
            return "QList<QObject*>" if self.resolve_class(m.group(1), ctx) else None
        m = re.fullmatch(r"QQmlListProperty<(.+)>", t)
        if m:
            cls = self.resolve_class(m.group(1), ctx)
            return f"QQmlListProperty<{self.ref(cls)}>" if cls else None
        if t.endswith("*"):
            cls = self.resolve_class(t[:-1], ctx)
            return f"{self.ref(cls)}*" if cls else None
        if re.fullmatch(r"[\w:]+", t):
            return self.resolve_enum(t, ctx, emitted)
        return None

    @staticmethod
    def by_value(t):
        return t in VALUE_TYPES or t.endswith("*") or t == "int" or "::E" in t or t in QT_ENUMS

    def param(self, t):
        return t if self.by_value(t) else f"const {t}&"

    # -- ordering ---------------------------------------------------------
    def order(self):
        deps = {}
        for name in self.roots:
            c = self.moc[name]
            d = set()
            if c["superclass"] in self.roots:
                d.add(c["superclass"])
            types = [p["type"] for p in c["properties"]]
            types += [a["type"] for k in ("signals", "slots", "invokables") for m in c[k] for a in m["args"]]
            types += [m["return"] for k in ("slots", "invokables") for m in c[k]]
            for t in types:
                owner = self.enum_owner_of(t, name)
                if owner in self.roots and owner != name:
                    d.add(owner)
            deps[name] = d
        out, done = [], set()
        pending = sorted(deps)
        while pending:
            ready = [n for n in pending if deps[n] <= done]
            if not ready:  # enum cycle: emit one whose superclass is done, its enum refs fall back to int
                ready = [next(n for n in pending if self.moc[n]["superclass"] not in self.roots
                              or self.moc[n]["superclass"] in done)]
            for n in ready:
                out.append(n)
                done.add(n)
            pending = [n for n in pending if n not in done]
        return out

    # -- emission ---------------------------------------------------------
    def enum_decls(self, c, member_names, indent):
        lines, seen_keys, seen = [], set(), set()
        for e in c["enums"]:
            if e["name"] in seen:
                continue
            seen.add(e["name"])
            values = sorted(e["values"].items(), key=lambda kv: (kv[1], kv[0]))
            keys = {k for k, _ in values}
            scoped = e["scoped"] or bool(keys & seen_keys) or bool(keys & member_names) or bool(keys & CPP_KEYWORDS)
            if not scoped:
                seen_keys |= keys
            macros = sorted(keys & MACROS)
            lo, hi = min(v for _, v in values), max(v for _, v in values)
            base = "" if -2**31 <= lo and hi < 2**31 else " : qint64"
            body = ", ".join(f"{k} = {v}" for k, v in values)
            for mac in macros:
                lines.append(f'#pragma push_macro("{mac}")\n#undef {mac}')
            lines.append(f"{indent}enum {'class ' if scoped else ''}{e['name']}{base} {{ {body} }};")
            for mac in macros:
                lines.append(f'#pragma pop_macro("{mac}")')
            lines.append(f"{indent}{'Q_ENUM_NS' if c['superclass'] is None else 'Q_ENUM'}({e['name']})")
        return lines

    def emit_namespace(self, c):
        ns = c["class"]
        lines = [f"namespace cip::{ns} {{", "Q_NAMESPACE"]
        if "QML.Element" in c.get("classinfo", {}):
            lines.append(f'Q_CLASSINFO("QML.Element", "{c["classinfo"]["QML.Element"]}")')
        lines += self.enum_decls(c, set(), "")
        lines.append(f"}} // namespace cip::{ns}\n")
        return "\n".join(lines)

    def arglist(self, m, ctx, emitted, names=True):
        out = []
        for i, a in enumerate(m["args"]):
            t = self.cpp_type(a["type"], ctx, emitted)
            if t is None:
                return None
            n = a.get("name") or f"a{i}"
            if n in CPP_KEYWORDS or n in MACROS or not re.fullmatch(r"[A-Za-z_]\w*", n):
                n = f"a{i}"
            out.append((self.param(t), n))
        if names:
            seen = set()
            for i, (t, n) in enumerate(out):
                if n in seen:
                    out[i] = (t, f"a{i}")
                seen.add(out[i][1])
        return out

    def emit_class(self, name, emitted):
        c = self.moc[name]
        ns, short = split_ns(self.cpp_path(name))
        root = self.roots[name]
        sup = c["superclass"]
        base = self.ref(sup) if sup in self.roots else sup
        ctor_parent = QT_ROOTS[root][1]
        reserved = set().union(*(RESERVED[r] for r in ROOT_RESERVED[root]))
        skip = self.skipped[name].append

        # Properties
        props, getters, setters = [], {}, {}
        signal_names = {s["name"] for s in c["signals"]}
        inherited_signals = {s["name"] for a in self.ancestors(name) for s in self.moc[a]["signals"]}
        for p in c["properties"]:
            pname = p["name"]
            t = self.cpp_type(p["type"], name, emitted)
            if t is None:
                skip(f"property {p['type']} {pname}: type")
                continue
            if pname in reserved or pname in MACROS:
                skip(f"property {p['type']} {pname}: name")
                continue
            props.append((p, t))
            getters[pname] = t
            if "WRITE" in p["flags"]:
                setters["set" + pname[:1].upper() + pname[1:]] = t

        # Methods (signals, public slots, public invokables)
        def methods(kind):
            out, seen = [], set()
            for m in c[kind]:
                if kind != "signals" and m["access"] != "public":
                    continue
                mname = m["name"]
                ret = "void" if kind == "signals" else self.cpp_type(m["return"], name, emitted)
                args = self.arglist(m, name, emitted)
                sig = f"{m['return']} {mname}({', '.join(a['type'] for a in m['args'])})"
                if ret is None or args is None:
                    skip(f"{kind[:-1]} {sig}: type")
                    continue
                if mname in reserved or mname in CPP_KEYWORDS or mname in MACROS:
                    skip(f"{kind[:-1]} {sig}: name")
                    continue
                if (mname in getters and not args) or (mname in setters and len(args) == 1):
                    continue
                if kind != "signals" and mname in signal_names | inherited_signals:
                    skip(f"{kind[:-1]} {sig}: shadows a signal")
                    continue
                if kind == "signals" and mname in getters:
                    skip(f"signal {sig}: shadows property getter")
                    continue
                key = (mname, tuple(t for t, _ in args))
                if key in seen:
                    continue
                seen.add(key)
                out.append((mname, ret, args))
            return out

        signals = methods("signals")
        declared_signals = {s for s, _, _ in signals}
        slots = [m for m in methods("slots")]
        slot_keys = {(n, tuple(t for t, _ in a)) for n, _, a in slots}
        invokables = [m for m in methods("invokables") if (m[0], tuple(t for t, _ in m[2])) not in slot_keys]
        sig_args = {s: a for s, _, a in signals}

        enum_member_names = set(getters) | set(setters) | {n for n, _, _ in signals + slots + invokables}
        lines = []
        lines.append(f"namespace cip{''.join('::' + n for n in ns)} {{")
        lines.append(f"class {short} : public {base}")
        lines.append("{")
        lines.append("    Q_OBJECT")
        for k, v in c.get("classinfo", {}).items():
            if not k.startswith("QML."):
                lines.append(f'    Q_CLASSINFO("{k}", "{v}")')
        for p, t in props:
            pname = p["name"]
            decl = f"    Q_PROPERTY({t} {pname} READ {getter_name(pname)}"
            setter = "set" + pname[:1].upper() + pname[1:]
            if "WRITE" in p["flags"]:
                decl += f" WRITE {setter}"
            notify = p.get("notify")
            if notify and (notify in declared_signals or notify in inherited_signals):
                decl += f" NOTIFY {notify}"
            elif notify:
                skip(f"property {pname}: NOTIFY {notify} not generated")
            if "CONSTANT" in p["flags"]:
                decl += " CONSTANT"
            if "FINAL" in p["flags"]:
                decl += " FINAL"
            lines.append(decl + ")")
        lines.append("public:")
        lines += self.enum_decls(c, enum_member_names, "    ")
        lines.append(f"    explicit {short}({ctor_parent}* parent = nullptr) : {base}(parent) {{}}")
        if sup == "QAbstractListModel":
            lines.append("    int rowCount(const QModelIndex& = {}) const override { return 0; }")
            lines.append("    QVariant data(const QModelIndex&, int) const override { return {}; }")
        if sup == "QQuickPaintedItem":
            lines.append("    void paint(QPainter*) override {}")
        for p, t in props:
            pname = p["name"]
            lines.append(f"    virtual {t} {getter_name(pname)}() const {{ return m_{pname}; }}")
            if "WRITE" in p["flags"]:
                notify = p.get("notify")
                emit = ""
                if notify in declared_signals:
                    a = sig_args[notify]
                    if not a:
                        emit = f" Q_EMIT {notify}();"
                    elif len(a) == 1 and a[0][0] in (t, self.param(t)):
                        emit = f" Q_EMIT {notify}(m_{pname});"
                elif notify in inherited_signals:
                    emit = f' QMetaObject::invokeMethod(this, "{notify}");'
                setter = "set" + pname[:1].upper() + pname[1:]
                guard = f" if (::cip::unchanged(m_{pname}, v)) return;" if emit else ""
                lines.append(f"    virtual void {setter}({self.param(t)} v) {{{guard} m_{pname} = v;{emit} }}")
        for kind, ms in (("public Q_SLOTS:", slots), ("public:", invokables)):
            if not ms:
                continue
            lines.append(kind)
            for mname, ret, args in ms:
                params = ", ".join(f"{t} {n}" for t, n in args)
                unused = "".join(f" Q_UNUSED({n});" for _, n in args)
                body = f"{{{unused} }}" if ret == "void" else f"{{{unused} return {{}}; }}"
                inv = "Q_INVOKABLE " if kind == "public:" else ""
                lines.append(f"    {inv}virtual {ret} {mname}({params}) {body}")
        if signals:
            lines.append("Q_SIGNALS:")
            for mname, _, args in signals:
                lines.append(f"    void {mname}({', '.join(f'{t} {n}' for t, n in args)});")
        if props:
            lines.append("protected:")
            for p, t in props:
                m = re.fullmatch(r"QQmlListProperty<(.+)>", t)
                lines.append(f"    QList<{m.group(1)}*> m_{p['name']}{{}};" if m else f"    {t} m_{p['name']}{{}};")
        lines.append("};")
        lines.append(f"}} // namespace cip{''.join('::' + n for n in ns)}\n")
        # A QQmlListProperty getter exposes its QList member (QML can append and assign).
        text = "\n".join(lines)
        text = re.sub(r"(QQmlListProperty<[^>]+>) (\w+)\(\) const \{ return (m_\w+); \}",
                      rf"\1 \2() const {{ auto* self = const_cast<{short}*>(this); return \1(self, &self->\3); }}", text)
        return text

    # -- files ------------------------------------------------------------
    def write(self, out: Path, chunks: int, qml_dir: Path | None):
        out.mkdir(parents=True, exist_ok=True)
        order = self.order()
        ns_names = {n["class"] for n in self.namespaces}
        emitted = set(ns_names)
        bodies = []
        for name in order:
            bodies.append((name, self.emit_class(name, emitted)))
            emitted.add(name)

        files = {}
        fwd = [HEADER, "#pragma once", "", "#include <QtCore/QObject>", ""]
        for name in order:
            ns, short = split_ns(self.cpp_path(name))
            fwd.append(f"namespace cip{''.join('::' + n for n in ns)} {{ class {short}; }}")
        fwd += ["", "namespace cip {",
                "// Binds a generated base to its handwritten implementation (see CIP_IMPLEMENT).",
                "template <class Base> struct Impl",
                "{",
                "    using type = Base;",
                "};",
                "",
                "// Generated setters notify only on change (CIP's setters compare first); types",
                "// without operator== (QJSValue, ...) always notify.",
                "template <class T> bool unchanged(const T& a, const T& b)",
                "{",
                "    if constexpr (requires { static_cast<bool>(a == b); })",
                "        return static_cast<bool>(a == b);",
                "    else",
                "        return false;",
                "}",
                "} // namespace cip", "",
                "// In cip_impl.h: CIP_IMPLEMENT(::cip::tibia::gamewindow::TFoo, ::tibia::gamewindow::TFoo);",
                "#define CIP_IMPLEMENT(BASE, IMPL) \\",
                "    template <> struct cip::Impl<BASE> { using type = IMPL; }", ""]
        files["cip_fwd.h"] = "\n".join(fwd)

        includes = ["#include <QtCore/QAbstractListModel>", "#include <QtCore/QSortFilterProxyModel>",
                    "#include <QtCore/QIdentityProxyModel>", "#include <QtCore/QJsonArray>",
                    "#include <QtCore/QJsonDocument>", "#include <QtCore/QJsonObject>", "#include <QtCore/QJsonValue>",
                    "#include <QtCore/QDateTime>", "#include <QtCore/QUrl>", "#include <QtCore/QVariant>",
                    "#include <QtCore/QPersistentModelIndex>", "#include <QtGui/QColor>", "#include <QtGui/QFont>",
                    "#include <QtGui/QImage>", "#include <QtGui/QKeySequence>", "#include <QtGui/QPainter>",
                    "#include <QtQml/QJSValue>", "#include <QtQml/QQmlListProperty>", "#include <QtQuick/QQuickItem>",
                    "#include <QtQuick/QQuickPaintedItem>", "#include <QtQuick/QQuickWindow>"]
        per = max(1, -(-len(bodies) // chunks))
        for i in range(chunks):
            part = bodies[i * per:(i + 1) * per]
            h = [HEADER, "#pragma once", ""]
            h += ['#include "cip_fwd.h"'] + includes if i == 0 else [f'#include "cip_gen_{i - 1:02d}.h"']
            h += ['', 'Q_MOC_INCLUDE("cip_gen.h")', ""]
            if i == 0:
                h += [self.emit_namespace(n) for n in self.namespaces]
            h += [b for _, b in part]
            files[f"cip_gen_{i:02d}.h"] = "\n".join(h)
            files[f"cip_gen_{i:02d}.cpp"] = f'{HEADER}#include "cip_gen.h"\n\n#include "moc_cip_gen_{i:02d}.cpp"\n'
        files["cip_gen.h"] = f'{HEADER}#pragma once\n\n#include "cip_gen_{chunks - 1:02d}.h"\n'

        opt = [HEADER, "#pragma once", "", "#include <array>", "#include <cstdint>", "#include <string_view>", "",
               "namespace cip {", "", "// Option ids as CIP sends and stores them (clientoptions.json keys).",
               "enum class EClientOption : std::uint8_t", "{"]
        opt += [f"    {v} = {k}," for k, v in self.options.items()]
        opt += ["};", "",
                f"inline constexpr std::array<std::string_view, {len(self.options)}> ClientOptionNames = {{"]
        opt += [f'    "{v}",' for v in self.options.values()]
        opt += ["};", "", "} // namespace cip", ""]
        files["cip_options.h"] = "\n".join(opt)

        files["cip_registration.h"] = "\n".join([
            HEADER, "#pragma once", "", "namespace cip {",
            "// Registers module qmlcomponents (native elements, TibiaEnums) and module",
            "// qmlenumvalues (enum-only scopes) exactly as CIP's client does.",
            "void registerQmlTypes();", "} // namespace cip", ""])
        reg = [HEADER, '#include "cip_registration.h"', '#include "cip_gen.h"', "",
               "#include <QtQml/qqml.h>", "",
               '#if __has_include("cip_impl.h")', '#include "cip_impl.h"', "#endif", "",
               "namespace cip {", "", "void registerQmlTypes()", "{"]
        for qname, e in sorted(self.elements.items()):
            cls = e["class"]
            if cls in ns_names:
                reg.append(f'    qmlRegisterUncreatableMetaObject({self.ref(cls)}::staticMetaObject, "qmlcomponents", 1, 0, '
                           f'"{qname}", "{qname} only provides enums");')
                continue
            if cls not in self.roots:
                print(f"[gen_cpp] element {qname}: {cls} is not generated", file=sys.stderr)
                continue
            impl = f"typename Impl<{self.ref(cls)}>::type"
            if e.get("singleton"):
                reg.append(f'    qmlRegisterSingletonType<{impl}>("qmlcomponents", 1, 0, "{qname}", '
                           f'[](QQmlEngine*, QJSEngine*) -> QObject* {{ return new {impl}; }});')
            elif not e.get("creatable", True):
                reason = (e.get("uncreatable_reason") or f"{qname} is created by the client").replace('"', '\\"')
                reg.append(f'    qmlRegisterUncreatableType<{impl}>("qmlcomponents", 1, 0, "{qname}", "{reason}");')
            else:
                reg.append(f'    qmlRegisterType<{impl}>("qmlcomponents", 1, 0, "{qname}");')
        reason = self.regs["enum_reason"].replace('"', '\\"')
        for qname, cls in sorted(self.regs["enum_scopes"].items()):
            if cls not in self.roots:
                print(f"[gen_cpp] enum scope {qname}: {cls} is not generated", file=sys.stderr)
                continue
            reg.append(f'    qmlRegisterUncreatableMetaObject({self.ref(cls)}::staticMetaObject, '
                       f'"{self.regs["enum_uri"]}", 1, 0, "{qname}", "{reason}");')
        reg += ["}", "", "} // namespace cip", ""]
        files["cip_registration.cpp"] = "\n".join(reg)

        if qml_dir:
            # CIP builds qmlcomponents with qt_add_qml_module; its qmldir is not in the
            # binary, so list the QML files as module types (paths as in CIP's qrc).
            # CIP files use Controls and GraphicalEffects types (ButtonGroup,
            # LinearGradient) with only `import qmlcomponents`: the module re-exports them.
            qmldir = ["module qmlcomponents", "import QtQuick.Controls", "import Qt5Compat.GraphicalEffects"]
            singletons = []
            for f in sorted((qml_dir / "qml").glob("*.qml")):
                single = re.search(r"^pragma Singleton", f.read_text(errors="replace"), re.M)
                qmldir.append(f"{'singleton ' if single else ''}{f.stem} 1.0 qml/{f.name}")
                if single:
                    singletons.append(f"singleton {f.stem} 1.0 {f.name}")
            files["qrc/qt/qml/qmlcomponents/qmldir"] = "\n".join(qmldir) + "\n"
            files["qrc/qt/qml/qmlcomponents/qml/qmldir"] = "\n".join(singletons) + "\n"

        files["cip_skipped.json"] = json.dumps(dict(sorted(self.skipped.items())), indent=1) + "\n"
        for fname, text in files.items():
            path = out / fname
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_text() != text:
                path.write_text(text)
        n_skip = sum(len(v) for v in self.skipped.values())
        print(f"[gen_cpp] {len(order)} classes, {len(self.namespaces)} enum namespaces, "
              f"{len(self.elements)} elements, {len(self.regs['enum_scopes'])} enum scopes, "
              f"{len(self.options)} options; {n_skip} members skipped (cip_skipped.json)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("contract", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--chunks", type=int, default=12)
    ap.add_argument("--qml", type=Path, help="client/upstream/qml/qmlcomponents (emits qrc/.../qmldir)")
    args = ap.parse_args()
    Gen(args.contract).write(args.out, args.chunks, args.qml)


if __name__ == "__main__":
    main()
