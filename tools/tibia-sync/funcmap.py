def stamp_token(sha256_hex: str) -> str:
    h = sha256_hex.strip().lower()
    if len(h) < 16 or any(c not in "0123456789abcdef" for c in h):
        raise ValueError(f"bad sha256: {sha256_hex!r}")
    return f"{SCHEME}/{h[:16]}"


def is_noise_symbol(symbol: str, method: str, size: int = 0) -> bool:
    if method in NOISE_METHODS:
        return True
    if _NOISE_METHOD_RE.match(method):
        cls = symbol.rsplit("::", 2)[-2] if "::" in symbol else ""
        if cls in _PLAY_PATH_V_CLASSES and size >= _PLAY_PATH_V_MIN_SIZE:
            return False
        return True
    low = symbol.lower()
    return any(tok in low for tok in _NOISE_SYMBOL_SUB)


def load_funcmap(path: Path) -> list[dict]:
    rows: list[dict] = []
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("FN_DONE"):
            continue
        if line.startswith("FN "):
            line = line[3:].strip()
        if not line.startswith("{"):
            continue
        obj = json.loads(line)
        sym = (obj.get("symbol") or "").strip()
        sha = (obj.get("sha256") or "").strip().lower()
        if not sym or not sha:
            continue
        addr = str(obj.get("addr") or "").strip()
        if addr and not addr.lower().startswith("0x"):
            try:
                addr = hex(int(addr, 16))
            except ValueError:
                addr = "0x" + addr
        rows.append({
            "symbol": sym,
            "addr": addr,
            "size": int(obj.get("size") or 0),
            "sha256": sha,
            "stamp": stamp_token(sha),
        })
    return rows



def normalize_ns(ns: list[str]) -> tuple[str, ...]:
    """Ensure tip-facing tibia:: prefix for CIP area namespaces."""
    if not ns:
        return ("tibia",)
    if ns[0] == "tibia" or ns[0] == "cipsoft":
        return tuple(ns)
    if ns[0] in _CIP_AREAS:
        return ("tibia",) + tuple(ns)
    return tuple(ns)


def _is_product_symbol(parts: list[str], symbol: str) -> bool:
    """Keep CIP / tip product types; drop STL, Qt internals, lambdas."""
    joined = "::".join(parts)
    if any(p.startswith("std") or p.startswith("__") for p in parts):
        return False
    if "lambda" in joined.lower() or "abi:" in symbol or "<" in symbol:
        return False
    if any(len(p) > 80 for p in parts):
        return False
    if "tibia" in parts or "cipsoft" in parts:
        return True
    # names.txt style: gamewindow::TNPCTradeController::foo
    if parts and parts[0] in _CIP_AREAS:
        return True
    return False


def split_symbol(symbol: str, size: int = 0) -> tuple[list[str], str, str] | None:
    """Return (namespaces, class, method) or None if not Class::method shaped."""
    if "<" in symbol or "lambda" in symbol.lower() or "abi:" in symbol:
        return None
    sym = _CLEAN.sub("_", symbol.replace(" ", ""))
    sym = sym.split("(")[0]
    parts = [p for p in sym.split("::") if p]
    if len(parts) < 2:
        return None
    if not _is_product_symbol(parts, symbol):
        return None
    method = parts[-1]
    cls = parts[-2]
    if not method or method.startswith("~"):
        return None
    if is_noise_symbol(symbol, method, size=size):
        return None
    if f"{cls}::{method}" in _GHOST_KEYS:
        return None
    # Protobuf / codegen helpers (PlacementNew_, etc.) and Ghidra thunk stubs.
    if method.endswith("_") or method.startswith("Placement") or "thunk" in method:
        return None

    # Prefer CIP T* types; allow a few non-T helpers under tibia:: only.
    if not cls.startswith("T"):
        if "tibia" not in parts and parts[0] not in _CIP_AREAS:
            return None

    ns = list(normalize_ns(parts[:-2]))
    while len(ns) >= 2 and ns[0] == "tibia" and ns[1] == "tibia":
        ns = ns[1:]
    # Guard filesystem path length
    rel = "/".join(ns + [f"{cls}.h"])
    if len(rel) > 200:
        return None
    return ns, cls, method



def load_moc_signatures(contract_dir: Path | None) -> dict[str, str]:
    """Map Class::method → full declaration text (return + name + params)."""
    out: dict[str, str] = {}
    if contract_dir is None:
        return out
    moc_path = contract_dir / "moc.json"
    if not moc_path.is_file():
        return out
    moc = json.loads(moc_path.read_text(encoding="utf-8"))

    def cpp_type(t: str) -> str:
        return t.replace("QList<", "QList<").strip() or "void"

    def arglist(m: dict) -> str:
        parts = []
        for i, a in enumerate(m.get("args") or []):
            n = a.get("name") or f"a{i}"
            parts.append(f"{cpp_type(a.get('type') or 'QVariant')} {n}")
        return ", ".join(parts)

    for c in moc:
        short = c["class"].split("::")[-1]
        for kind in ("slots", "invokables"):
            for m in c.get(kind) or []:
                if m.get("access") and m["access"] != "public":
                    continue
                name = m["name"]
                ret = "void" if kind == "signals" else cpp_type(m.get("return") or "void")
                out[f"{short}::{name}"] = f"{ret} {name}({arglist(m)})"
        for p in c.get("properties") or []:
            pname = p["name"]
            t = cpp_type(p.get("type") or "QVariant")
            out[f"{short}::{pname}"] = f"{t} {pname}() const"
            if "WRITE" in (p.get("flags") or []):
                setter = "set" + pname[:1].upper() + pname[1:]
                out[f"{short}::{setter}"] = f"void {setter}({t} v)"
    return out


def group_rows(rows: list[dict]) -> dict[tuple[str, ...], dict[str, list[dict]]]:
    """ns_tuple → class → [rows]."""
    tree: dict[tuple[str, ...], dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    for row in rows:
        split = split_symbol(row["symbol"], size=int(row.get("size") or 0))
        if not split:
            continue
        ns, cls, method = split
        row = {**row, "class": cls, "method": method, "key": f"{cls}::{method}"}
        tree[tuple(ns)][cls].append(row)
    for ns in tree:
        for cls, items in tree[ns].items():
            seen: set[str] = set()
            uniq: list[dict] = []
            for it in sorted(items, key=lambda r: (r["method"], r["addr"])):
                if it["key"] in seen:
                    continue
                seen.add(it["key"])
                uniq.append(it)
            tree[ns][cls] = uniq
    return tree


def emit_class_header(
    ns: tuple[str, ...],
    cls: str,
    methods: list[dict],
    moc_sigs: dict[str, str] | None = None,
) -> str:
    moc_sigs = moc_sigs or {}
    lines = [HEADER.rstrip(), "#pragma once", ""]
    indent = ""
    for n in ns:
        lines.append(f"{indent}namespace {n} {{")
        indent += "  "
    lines.append(f"{indent}class {cls} {{")
    lines.append(f"{indent}public:")
    for m in methods:
        addr = m["addr"]
        stamp = m["stamp"]
        if addr:
            lines.append(f"{indent}  // {stamp} @ {addr}")
        else:
            lines.append(f"{indent}  // {stamp}")
        decl = moc_sigs.get(m["key"]) or f"void {m['method']}()"
        lines.append(f"{indent}  {decl};")
    lines.append(f"{indent}}};")
    for n in reversed(ns):
        indent = indent[2:]
        lines.append(f"{indent}}} // namespace {n}")
    lines.append("")
    return "\n".join(lines)


# /// CIP 0x100abcdef  or  /// CIP 0x… / 0x… (first addr wins for naming)
_TIP_CIP_ADDR = re.compile(
    r"///\s*CIP\s+(0x[0-9a-fA-F]+)(?:\s*/\s*0x[0-9a-fA-F]+)*\.?",
)
_TIP_METHOD = re.compile(
    r"\b(?:Q_INVOKABLE\s+)?(?:virtual\s+)?([\w:<>,\s\*\&]+?)\s+(\w+)\s*\([^;]*\)\s*(?:const\s*)?(?:override\s*)?;",
)
_TIP_CLASS = re.compile(r"\bclass\s+(T\w+)\b")
_TIP_NS = re.compile(r"\bnamespace\s+(\w+)\s*\{")


def _norm_addr(addr: str) -> str:
    a = addr.strip().lower()
    if a.startswith("00"):
        # Ghidra sometimes prints 00100abcdef
        a = hex(int(a, 16))
    if not a.startswith("0x"):
        a = hex(int(a, 16)) if a else a
    return a


def tip_addr_to_symbol(tip_roots: list[Path]) -> dict[str, str]:
    """Map 0xaddr → tibia::…::Class::method from tip /// CIP comments."""
    out: dict[str, str] = {}
    for root in tip_roots:
        if not root.is_dir():
            continue
        for path in root.rglob("*.h"):
            if "idleot" in path.parts:
                continue
            ns_stack: list[str] = []
            class_name: str | None = None
            pending_addr: str | None = None
            for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
                for nm in _TIP_NS.finditer(line):
                    # crude: push on `{` same line
                    if "{" in line[nm.end():] or line.rstrip().endswith("{"):
                        ns_stack.append(nm.group(1))
                if line.strip() == "}" or line.strip().startswith("} //"):
                    if ns_stack:
                        ns_stack.pop()
                cm = _TIP_CLASS.search(line)
                if cm and ("final" in line or ":" in line or "{" in line):
                    class_name = cm.group(1)
                am = _TIP_CIP_ADDR.search(line)
                if am:
                    pending_addr = _norm_addr(am.group(1))
                    continue
                # `using Alias = …` aliases are not Class::method stamps — drop the
                # pending CIP addr so a later free function is not mis-attributed.
                if pending_addr and line.lstrip().startswith("using "):
                    pending_addr = None
                    continue
                if pending_addr and class_name:
                    mm = _TIP_METHOD.search(line)
                    if mm:
                        method = mm.group(2)
                        ns = list(ns_stack)
                        if not ns or ns[0] != "tibia":
                            ns = list(normalize_ns(ns))
                        sym = "::".join(ns + [class_name, method])
                        out.setdefault(pending_addr, sym)
                        pending_addr = None
    return out


def attach_names_from_tip(rows: list[dict], tip_roots: list[Path]) -> list[dict]:
    """Prefer tip /// CIP 0xaddr names when the address matches a FUNCMAP row.

    Never rename noise (vtable/RTTI/moc): tip CIP comments often sit above a
    nearby free function and would otherwise mint false Class::method stamps.
    """
    by_addr = tip_addr_to_symbol(tip_roots)
    if not by_addr:
        return rows
    out = []
    for row in rows:
        addr = _norm_addr(str(row.get("addr") or ""))
        sym = str(row.get("symbol") or "")
        method = sym.rsplit("::", 1)[-1] if sym else ""
        if is_noise_symbol(sym, method, size=int(row.get("size") or 0)):
            out.append(row)
            continue
        named = by_addr.get(addr)
        if named:
            row = {**row, "symbol": named}
        out.append(row)
    return out


def macho_va_offset(buf: bytes, va: int) -> int | None:
    """File offset for a virtual address in a thin x86_64 Mach-O (same as proto_coverage)."""
    if len(buf) < 32 or buf[:4] != b"\xcf\xfa\xed\xfe":
        return None
    ncmds = struct.unpack_from("<I", buf, 16)[0]
    pos = 32
    for _ in range(ncmds):
        cmd, size = struct.unpack_from("<II", buf, pos)
        if cmd == 0x19:  # LC_SEGMENT_64
            vmaddr, vmsize, fileoff, filesize = struct.unpack_from("<QQQQ", buf, pos + 24)
            if vmaddr <= va < vmaddr + min(vmsize, filesize):
                return int(fileoff + (va - vmaddr))
        pos += size
    return None


def hash_macho_bytes(binary: Path, va: int, size: int) -> str | None:
    if size <= 0:
        return None
    buf = binary.read_bytes()
    off = macho_va_offset(buf, va)
    if off is None or off + size > len(buf):
        return None
    return hashlib.sha256(buf[off : off + size]).hexdigest()


def rows_from_tip_addrs(binary: Path, tip_roots: list[Path], default_size: int = 64) -> list[dict]:
    """Stamp rows for tip /// CIP addrs by hashing Mach-O bytes (no Ghidra function required).

    Size = gap to the next tip addr when available, else default_size (capped).
    """
    by_addr = tip_addr_to_symbol(tip_roots)
    if not by_addr or not binary.is_file():
        return []
    addr_sym = sorted((int(a, 16), sym) for a, sym in by_addr.items())
    rows: list[dict] = []
    for i, (va, sym) in enumerate(addr_sym):
        if i + 1 < len(addr_sym):
            size = max(16, min(addr_sym[i + 1][0] - va, 512))
        else:
            size = default_size
        sha = hash_macho_bytes(binary, va, size)
        if not sha:
            continue
        rows.append({
            "symbol": sym,
            "addr": hex(va),
            "size": size,
            "sha256": sha,
            "stamp": stamp_token(sha),
        })
    return rows



def merge_funcmap_and_tip(funcmap_rows: list[dict], tip_rows: list[dict]) -> list[dict]:
    """Union by addr; non-noise FUNCMAP hash/size wins on overlap.

    Tip Mach-O hashes use addr-gap sizing and are a fallback when Ghidra did not
    emit a product function. Noise FUNCMAP rows (vtable/RTTI/moc) must not
    overwrite tip product stamps — group_rows would drop them and leave tip
    implementations as unknown.
    Tip names are applied separately via attach_names_from_tip.
    """
    by_addr: dict[str, dict] = {}
    for row in tip_rows:
        by_addr[_norm_addr(row["addr"])] = row
    for row in funcmap_rows:
        addr = _norm_addr(row["addr"])
        sym = str(row.get("symbol") or "")
        method = sym.rsplit("::", 1)[-1] if sym else ""
        if is_noise_symbol(sym, method, size=int(row.get("size") or 0)):
            continue
        by_addr[addr] = row
    return list(by_addr.values())



def stamps_root_for(out_upstream: Path) -> Path:
    return out_upstream / "cip_stamps"


def write_stamp_headers(
    rows: list[dict],
    out_upstream: Path,
    contract_dir: Path | None = None,
) -> tuple[Path, int]:
    """Overwrite cip_stamps/ under the staged/vendored upstream tree."""
    root = stamps_root_for(out_upstream)
    if root.exists():
        for p in root.rglob("*"):
            if p.is_file():
                p.unlink()
        for p in sorted(root.rglob("*"), reverse=True):
            if p.is_dir():
                try:
                    p.rmdir()
                except OSError:
                    pass
    root.mkdir(parents=True, exist_ok=True)

    moc_sigs = load_moc_signatures(contract_dir or (out_upstream / "contract"))
    tree = group_rows(rows)
    includes: list[str] = []
    n_methods = 0
    for ns in sorted(tree.keys(), key=lambda t: "/".join(t)):
        for cls in sorted(tree[ns].keys()):
            methods = tree[ns][cls]
            n_methods += len(methods)
            rel = Path(*list(ns), f"{cls}.h")
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(emit_class_header(ns, cls, methods, moc_sigs), encoding="utf-8")
            includes.append(rel.as_posix())

    umbrella = [HEADER.rstrip(), "#pragma once", ""]
    for rel in includes:
        umbrella.append(f'#include "{rel}"')
    umbrella.append("")
    (root / "cip_stamps.h").write_text("\n".join(umbrella), encoding="utf-8")
    (root / "MANIFEST.txt").write_text(
        "\n".join(
            f"{r['stamp']} {r.get('key', r['symbol'])} {r.get('addr', '')}".strip()
            for r in sorted(
                (x for ns in tree.values() for ms in ns.values() for x in ms),
                key=lambda r: r.get("key", r["symbol"]),
            )
        )
        + "\n",
        encoding="utf-8",
    )
    return root, n_methods
