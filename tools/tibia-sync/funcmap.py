"""FUNCMAP → overwriteable CIP stamp headers (scheme b1).

FUNCMAP is JSONL from TibiaFunctionBodies.java (lines may be prefixed with `FN `).
Each record: symbol, addr, size, sha256.

Writes apps/qtclient/client/upstream/cip_stamps/** (always overwritten).
No tip .cpp rewriting — stamp_check compares header hashes to tip comments.

Optional contract/ moc.json enriches declarations with real signatures.
"""

